package minicode.com;

import org.springframework.boot.SpringApplication;
import org.springframework.boot.autoconfigure.SpringBootApplication;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.RestController;

@SpringBootApplication
@RestController
public class MiniLeetCodeApplication {

    private final UserRepo userRepo;

    public MiniLeetCodeApplication(UserRepo userRepo) {
        this.userRepo = userRepo;
    }

    @GetMapping("/hello")
    public String hello() {
        User foundUser = userRepo.findFirstByUserName("Alice").orElseGet(() -> {
            User user = new User();
            user.setUserName("Alice");
            user.setEmail("alice@example.com");

            // The ID is generated by the database, so we do not set it ourselves.
            return userRepo.save(user);
        });

        System.out.printf("Found user: %s, email: %s, id: %d%n",
                foundUser.getUserName(), foundUser.getEmail(), foundUser.getUserId());

        return String.format("Found user: %s, email: %s, id: %d",
                foundUser.getUserName(), foundUser.getEmail(), foundUser.getUserId());
    }

    public static void main(String[] args) {
        SpringApplication.run(MiniLeetCodeApplication.class, args);
    }

}
